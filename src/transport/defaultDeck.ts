export function resolveVoicePresetSummary(
  preset: StarterPresetId,
  voicePreset?: VoicePresetKind,
): string | null {
  const effective: VoicePresetKind =
    voicePreset ?? (preset === 'blank-canvas' ? 'pure-mic' : 'doubao-alt')
  switch (effective) {
    case 'doubao-alt':
      return 'Alt'
    case 'system-win-h':
      return 'Win+H'
    case 'ctrl-win':
      return 'Ctrl+Win'
    case 'pure-mic':
      return null
  }
}

